"""Render the case result as markdown.

Deliberately contains **no timestamp**. A generated report that stamps itself
with the wall clock changes on every run, so `git diff` stops meaning "a number
moved" and starts meaning "someone ran it again". The report dates itself by the
observation cutoffs instead, which is the only date that affects a result.
"""

from __future__ import annotations

from .pipeline import CaseResult


def _pct(value: float) -> str:
    return f"{value:.1%}"


def _verdict(driver) -> str:
    if driver.designed_sign is None:
        return "—"
    if driver.recovered is None:
        return "too weak to read"
    return "recovered" if driver.recovered else "**contradicted**"


def render(result: CaseResult) -> str:
    oot = result.out_of_time
    raw = result.out_of_time_uncalibrated
    oracle = result.out_of_time_oracle
    comparison = result.comparison
    economics = result.economics

    designed = [d for d in result.drivers if d.designed_sign is not None]
    recovered = sum(1 for d in designed if d.recovered is True)
    contradicted = sum(1 for d in designed if d.recovered is False)

    lines: list[str] = []
    add = lines.append

    add("# Churn without leakage — results")
    add("")
    add("Generated by `uv run run.py`. Every number below is reproducible from the seed;")
    add("nothing here is hand-entered. Synthetic data — see `../data-model/DATA_CARD.md`.")
    add("")

    add("## The setup")
    add("")
    add("| | Training | Scoring |")
    add("|---|---|---|")
    add(f"| Observation cutoff | {result.train.cutoff} | {result.test.cutoff} |")
    add(f"| Customers | {len(result.train):,} | {len(result.test):,} |")
    add(f"| Churned in the next 90 days | {_pct(result.train.base_rate)} | {_pct(result.test.base_rate)} |")
    add(f"| Excluded (churned in the earlier window) | — | {result.test.excluded_already_churned:,} |")
    add("")
    add(f"Features are built strictly from facts dated on or before each cutoff. "
        f"{result.n_fit:,} customers are used to fit the model and {result.n_calibration:,} are held back "
        f"for calibration, so the calibrator never sees the data its calibration is reported on.")
    add("")
    add("The scoring population excludes customers who churned during the earlier window: they are gone, "
        "and scoring a model on customers who already left measures nothing. That exclusion is also why the "
        "two base rates differ — the surviving base is lower-risk than the one the model was trained on.")
    add("")

    add("## Three readings of the same model")
    add("")
    add("The same features and the same estimator, evaluated three ways. Only the first is honest.")
    add("")
    add("| Reading | AUC | What it actually measures |")
    add("|---|---|---|")
    add(f"| **Out of time** (fit at {result.train.cutoff}, scored at {result.test.cutoff}) | **{oot.auc:.3f}** "
        f"| Whether the model generalises *forward*, which is the only thing production asks of it |")
    add(f"| In-time random split | {result.in_time.auc:.3f} "
        f"| Whether it generalises to customers it did not see, in the period it was fitted on |")
    add(f"| With one post-outcome feature | {result.with_leakage.auc:.3f} "
        f"| Nothing. The feature is derived from the label |")
    add("")
    gap = result.optimism_gap
    noise = 2.0 * oot.auc_standard_error
    add(f"A random split reads **{gap:+.3f} AUC** against the out-of-time result — and that is where the "
        f"reporting has to stay honest. The out-of-time AUC carries a standard error of "
        f"±{oot.auc_standard_error:.3f} (Hanley–McNeil), so a gap of {abs(gap):.3f} is "
        f"{'inside' if abs(gap) < noise else 'outside'} two standard errors. "
        + ("**This dataset does not establish that the in-time reading is optimistic.** It usually is, and the "
           "generating process here is stationary by construction so there is little drift for it to miss — "
           "but the honest statement is that the difference is within noise."
           if abs(gap) < noise else
           "The difference is larger than sampling noise on this run.")
        )
    add("")
    add("The reason to evaluate out of time is therefore **methodological, not empirical**. A random split "
        "answers a question production never asks — *how does this do on customers I have not seen, during the "
        "period I fitted on?* — and it cannot detect drift, seasonality, or a population that has changed shape, "
        "because it holds none of them out. On a real base those effects are the difference between a model that "
        "works and one that quietly stopped working. The number to publish is the first row, and it would still "
        "be the first row if the gap were zero.")
    add("")
    add(f"The third row is the one worth sitting with: adding a single field derived from the outcome takes AUC "
        f"to {result.with_leakage.auc:.3f}. Nothing errors, no test fails, and the model is worthless. Leakage "
        f"does not announce itself — it shows up as a result good enough that nobody questions it.")
    add("")

    add("## Does it rank, and does it mean anything?")
    add("")
    add("Two different questions. A model can pass the first and fail the second.")
    add("")
    add("| Metric | Value | Reading |")
    add("|---|---|---|")
    add(f"| AUC | {oot.auc:.3f} ± {oot.auc_standard_error:.3f} | Ranking. Typical for churn on behavioural "
        f"features |")
    add(f"| KS | {oot.ks:.3f} | Separation between churners and stayers |")
    add(f"| Top-decile lift | {oot.top_decile_lift:.2f}× | The riskiest 10% churn "
        f"{oot.top_decile_lift:.2f}× the base rate |")
    add(f"| Top-decile capture | {_pct(oot.top_decile_capture)} | Share of all churn sitting in that 10% |")
    add(f"| Brier score | {oot.brier:.4f} | Probability accuracy (lower is better) |")
    add(f"| Log loss | {oot.log_loss:.4f} | Penalises confident mistakes |")
    add(f"| Expected calibration error | {oot.expected_calibration_error:.4f} | Mean gap between promised "
        f"and observed risk |")
    add(f"| Calibration slope | {oot.calibration_slope:.2f} | 1.00 = confidence exactly right; "
        f"below 1 = overconfident |")
    add("")
    add("Accuracy is deliberately absent. With a base rate of "
        f"{_pct(oot.base_rate)}, predicting \"nobody churns\" scores "
        f"{_pct(1 - oot.base_rate)} accuracy and is worth nothing.")
    add("")
    add("![Calibration](calibration.svg)")
    add("")
    add(f"**Calibration is where the time gap shows.** The slope is {oot.calibration_slope:.2f}, not 1.00: "
        f"the model is overconfident six months on. It predicts {_pct(oot.mean_predicted)} churn on average "
        f"against {_pct(oot.base_rate)} observed. Recalibrating on the training period does not fix this "
        f"(ECE {raw.expected_calibration_error:.4f} raw vs {oot.expected_calibration_error:.4f} after Platt "
        f"scaling) — the base rate moved *after* the calibrator was fitted, and no adjustment made on old data "
        f"anticipates that. The calibrated model is what every figure above and below uses; that the raw one "
        f"scores marginally better here is the finding, not a reason to drop the step. Holding data out to "
        f"calibrate remains correct method; what it cannot do is see forward.")
    add("")
    add(f"With hindsight the ceiling is ECE {oracle.expected_calibration_error:.4f} and slope "
        f"{oracle.calibration_slope:.2f} — recalibrating on the outcomes we were trying to predict. That is not "
        f"achievable in production; it is reported to separate the two failure modes. The ranking is fine. Only "
        f"the level has drifted. So the operational answer is not a better model: it is to recalibrate against "
        f"the most recent closed window and to alarm on predicted-vs-actual base rate as a drift monitor.")
    add("")
    add("![Cumulative gains](gains.svg)")
    add("")

    add("## What drives it")
    add("")
    add("Coefficients on standardised features, so they are comparable across features. Two columns, because "
        "they answer different questions: **marginal** is the effect on its own — what a stakeholder means by "
        "\"do unhappy customers churn more?\" — and **conditional** is the effect given every other feature, "
        "which is what the model uses. Quoting the second as if it were the first is how an explainable model "
        "gets explained wrong.")
    add("")
    inconclusive = len(designed) - recovered - contradicted
    add(f"Because this dataset's causal structure is *known* (`data-model/telco/config.py`), the last column is "
        f"a real check rather than a matter of taste. Of the {len(designed)} designed drivers that survive "
        f"pruning: **{recovered} recovered** with the correct sign, **{contradicted} contradicted**, "
        f"and **{inconclusive} are too weak to read individually** — their marginal effect is smaller than its "
        f"own standard error. That last group is not a failure: some drivers are deliberately weak by design "
        f"(a payment-problem *rate* around 0.1 against a weight of 1.1 moves the log-odds by about 0.11), and "
        f"reporting the sign of a coefficient smaller than its noise would be the analytical error, not the "
        f"finding.")
    add("")
    add("| Feature | Conditional | Marginal | ± 2 s.e. | Designed | Verdict |")
    add("|---|---:|---:|---:|:---:|---|")
    for d in result.drivers:
        sign = {1: "+", -1: "−", None: "—"}[d.designed_sign]
        flip = " ⇄" if d.flips_when_conditioned else ""
        add(f"| `{d.name}`{flip} | {d.coefficient:+.3f} | {d.marginal_coefficient:+.3f} "
            f"| ±{2 * d.marginal_standard_error:.3f} | {sign} | {_verdict(d)} |")
    add("")
    add("*⇄ marks a feature whose sign changes once the other features are present — not a bug, and not "
        "leakage: it means another feature already carries its information.*")
    add("")
    if result.dropped_features:
        add("Three features were dropped before the coefficients were read, because each duplicated one already "
            "kept:")
        add("")
        for dropped, kept, correlation in result.dropped_features:
            add(f"- `{dropped}` — correlated {correlation:+.3f} with `{kept}`")
        add("")
        add("This is not about accuracy; the ridge penalty absorbs collinearity and AUC barely moves. It is "
            "about the deliverable. Fitted unpruned, this model reports that *an unresolved escalation reduces "
            "churn* — the exact opposite of how the data was built. A model whose explanation is wrong is worse "
            "than one with no explanation, because someone will act on it.")
        add("")

    retention = next((d for d in result.drivers if d.name == "retention_offer_taken"), None)
    if retention is not None:
        add(f"**The most interesting row is `retention_offer_taken`.** On its own it looks inert "
            f"({retention.marginal_coefficient:+.3f}, inside its own noise). Conditional on risk it is one of "
            f"the strongest protective effects in the model ({retention.coefficient:+.3f}). That is confounding, "
            f"and it is in the data on purpose: retention campaigns were *targeted at high-risk customers*, so "
            f"the raw comparison hides a real effect. Untangling it properly needs the held-out control group — "
            f"which is case 05, not this one. Here it is a warning: this coefficient is not a campaign ROI, and "
            f"reporting it as one would be wrong.")
        add("")

    add("## The decision: who do we actually call?")
    add("")
    add("A churn model retains nobody. A retention action does, and there is budget for a fraction of the base. "
        "So the deliverable is a contact list, and the ranking that builds it is a commercial choice, not a "
        "statistical one.")
    add("")
    add("| Assumption | Value |")
    add("|---|---|")
    add(f"| Cost per contact | {economics.contact_cost:.2f} |")
    add(f"| Cost of the offer, when accepted | {economics.offer_cost:.2f} |")
    add(f"| Share of would-be churners a contact retains | {_pct(economics.save_rate)} |")
    add(f"| Contribution margin | {_pct(economics.margin)} |")
    add(f"| Value horizon | {economics.horizon_months} months |")
    add("")
    add("These are the retention team's numbers, not measurements. Every figure below inherits them.")
    add("")
    add("![Profit by capacity](profit.svg)")
    add("")
    add(f"At a budget of {comparison.capacity:,} contacts ({_pct(comparison.capacity / len(result.test))} of the "
        f"base):")
    add("")
    add("| Targeting | Realised profit |")
    add("|---|---:|")
    add(f"| Ranked by predicted risk | {comparison.by_risk.profit_at(comparison.capacity):,.0f} |")
    add(f"| Ranked by expected value | {comparison.by_value.profit_at(comparison.capacity):,.0f} |")
    add(f"| **Difference** | **{comparison.uplift_at_capacity:+,.0f}** |")
    add("")
    add(f"Same model, same probabilities, same budget — **{comparison.uplift_at_capacity:+,.0f}** from changing "
        f"only the sort order. The two lists share just {_pct(comparison.overlap_at_capacity)} of their names: "
        f"ranking by risk promotes customers who are likely to leave but cheap to lose, and a contact spent "
        f"there is a contact not spent on someone worth keeping.")
    add("")
    risk_n, risk_profit = comparison.by_risk.optimal
    value_n, value_profit = comparison.by_value.optimal
    add(f"The curves also peak in different places. Risk-ranked peaks at {risk_n:,} contacts "
        f"({risk_profit:,.0f}); value-ranked peaks at {value_n:,} ({value_profit:,.0f}) — **more profit from "
        f"fewer calls.** Contacting the entire base returns {comparison.contact_all:,.0f}, which is what "
        f"happens when the model is used to justify a campaign rather than to size one.")
    add("")

    add("## Limitations")
    add("")
    add("- **The save rate is assumed, not measured.** Realised profit applies a flat "
        f"{_pct(economics.save_rate)} to customers who did churn. Whether a contact *caused* a save is "
        "unknowable without a control group — that is case 05, and until it exists these figures are a "
        "planning model, not a measured return.")
    add("- **One historical split.** Two cutoffs give one out-of-time estimate, not a distribution. A rolling "
        "backtest over several cutoffs would put an error bar on the AUC gap; this reports a point.")
    add("- **Synthetic data, with a known generating process.** That is what makes the driver check possible, "
        "and it also means the model is not being tested against the messiness that breaks real pipelines: "
        "missing history, merged accounts, plan migrations, delayed billing.")
    add("- **Consent is static** in the data model, so it cannot be re-derived as of a past cutoff. It is not "
        "used here; case 03 has to confront it.")
    add("- **A 90-day window is a choice.** Shorter windows raise precision and shrink the base of actionable "
        "churn; longer ones do the reverse. Nothing here establishes that 90 days is the right horizon for a "
        "given retention operation.")
    add("")

    add("## What would make this good enough to deploy")
    add("")
    add("Stated as tests, not aspirations:")
    add("")
    add(f"- Top-decile capture stays above {_pct(oot.top_decile_capture)} on the next unseen cutoff.")
    add("- Calibration slope stays within 0.85–1.15, checked every cycle, with recalibration triggered on "
        "breach rather than on a schedule.")
    add("- Predicted vs actual base rate is monitored as a drift alarm — it moved here, and it will move again.")
    add("- The contact list is generated by expected value, not probability, and the economics behind it are "
        "reviewed with the retention team rather than assumed by the modeller.")
    add("- A held-out control on every retention campaign, so the save rate stops being an assumption.")
    add("")

    return "\n".join(lines) + "\n"
